    public void lerJTable() {
    DefaultTableModel modelo = (DefaultTableModel) tabela.getModel();
    modelo.setNumRows(0); // limpa a tabela

    AlunoDAO dao = new AlunoDAO();

    for (Aluno a : dao.lerTudo()) {
        String sx, st;

        // Define o sexo
        if (a.getSexo() == 0) {
            sx = "M";
        } else if (a.getSexo() == 1) {
            sx = "F";
        } else {
            sx = "O";
        }

        // Define a situação
        if (a.getSituacao() == 0) {
            st = "Aprovado";
        } else {
            st = "Reprovado";
        }

        // Adiciona a linha na tabela
        modelo.addRow(new Object[]{
            a.getId(),
            a.getNome(),
            sx,
            a.getNota1(),
            a.getNota2(),
            a.getMedia(),
            st
        });
    }
}

