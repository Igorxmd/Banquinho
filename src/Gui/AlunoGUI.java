    private void CalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalcularActionPerformed
       double n1,n2,med;
n1 = Double.parseDouble(edtNota1.getText());
n2 = Double.parseDouble(edtNota2.getText());
med= (n1+n2)/2.0;
if(med>=6.0){
    txtSitua.setText("Aprovado");
    txtSitua.setForeground(Color.green);
}else{
    txtSitua.setText("Reprovado");
    txtSitua.setForeground(Color.red);
}
btnCadastrar.setEnabled(true);
edtMedia.setText(String.format("%.1f", med));
    }//GEN-LAST:event_CalcularActionPerformed

