    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        if (edtNome.getText().isEmpty() || edtNota1.getText().isEmpty() || edtNota2.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Os campos nome, nota 1 e nota 2 devem ser preenchidos.");
        }else{
            Aluno aluno = new Aluno();
aluno.setNome(edtNome.getText());
if(btnFeminino.isSelected())
    aluno.setSexo(0);
else if(btnMasculino.isSelected())
    aluno.setSexo(1);
else
    aluno.setSexo(2);
aluno.setApagado(0);
aluno.setNota1(Double.parseDouble(edtNota1.getText()));
aluno.setNota2(Double.parseDouble(edtNota2.getText()));
aluno.setMedia((aluno.getNota1()+aluno.getNota2())/2);
if(aluno.getMedia()>=6.0)
    aluno.setSituacao(0);
else
    aluno.setSituacao(1);
try {
    AlunoDAO dao = new AlunoDAO();
    dao.adiciona(aluno);
    JOptionPane.showMessageDialog(null, "Aluno adicionado!");

    btnCadastrar.setEnabled(false);
    edtNome.setText("");
    edtNota1.setText("");
    edtNota2.setText("");
    edtMedia.setText("");
    txtSitua.setText("---");
    buttonGroup1.clearSelection();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(null, "Erro ao cadastrar aluno: " + ex.getMessage());
}
            
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

